import test, { before, after } from 'node:test';
import assert from 'node:assert/strict';
import { MongoMemoryReplSet } from 'mongodb-memory-server';
import request from 'supertest';
import mongoose from 'mongoose';
import crypto from 'node:crypto';
process.env.NODE_ENV='test';
process.env.JWT_SECRET=crypto.randomBytes(40).toString('hex');
const {default:app}=await import('../index.js');
const {connectDB}=await import('../config/db.js');
const {default:Order}=await import('../models/Order.js');
const {default:Product}=await import('../models/Product.js');
let db,a,b,pa,pb;
const key=()=>crypto.randomUUID();
const body=(id,quantity=1,idempotencyKey=key())=>({idempotencyKey,customer:{name:'TEST Customer',phone:'03000000000',city:'Test City'},items:[{productId:id,quantity}]});
const post=(data,slug='order-test-a')=>request(app).post('/api/public/stores/'+slug+'/orders').send(data);
async function seller(email,slug){
 const password=crypto.randomBytes(20).toString('hex');
 await request(app).post('/api/auth/register').send({fullName:'TEST Seller',email,password}).expect(201);
 const auth=await request(app).post('/api/auth/login').send({email,password}).expect(200);
 const token=auth.body.data.token;
 await request(app).post('/api/stores').set('Authorization','Bearer '+token).send({name:'TEST Shop',slug,whatsappNumber:'03000000000'}).expect(201);
 const product=await request(app).post('/api/products').set('Authorization','Bearer '+token).send({title:'TEST Item',category:'Test',price:1200.5,stock:3,isActive:true}).expect(201);
 return {token,product:product.body.data.id};
}
before(async()=>{
 db=await MongoMemoryReplSet.create({replSet:{count:1}});
 await connectDB(db.getUri());a=await seller('order-a@example.invalid','order-test-a');b=await seller('order-b@example.invalid','order-test-b');pa=a.product;pb=b.product;
});
after(async()=>{await mongoose.disconnect();await db?.stop();});
test('guest orders use server prices, stay private, deduplicate and remain pending without stock deduction',async()=>{
 const payload={...body(pa,2),totalAmount:1};
 const first=await post(payload).expect(201);
 assert.equal(first.body.data.totalAmount,2401);
 assert.deepEqual(Object.keys(first.body.data).sort(),['orderNumber','status','totalAmount']);
 await post(payload).expect(200);
 assert.equal(await Order.countDocuments({orderNumber:first.body.data.orderNumber}),1);
 assert.equal((await Product.findById(pa)).stock,3);
 await post({...payload,items:[{productId:pa,quantity:1}]}).expect(409);
 await request(app).get('/api/orders').expect(401);
 await request(app).get('/api/public/stores/order-test-a/orders').expect(404);
});
test('rejects cross-store, invalid, inactive and insufficient-stock products',async()=>{
 await post(body(pb)).expect(400);
 await post(body(pa,-1)).expect(400);
 await post(body(pa,99)).expect(409);
 await post(body('invalid')).expect(400);
 await post({...body(pa),items:[{productId:pa,quantity:1},{productId:pa,quantity:1}]}).expect(400);
 await Product.updateOne({_id:pa},{$set:{isActive:false}});
 await post(body(pa)).expect(400);
 await Product.updateOne({_id:pa},{$set:{isActive:true}});
});
test('seller isolation, valid status transitions and transaction-safe concurrent stock confirmation',async()=>{
 const first=await post(body(pa,2)).expect(201);
 const second=await post(body(pa,2)).expect(201);
 const firstOrder=await Order.findOne({orderNumber:first.body.data.orderNumber});
 const secondOrder=await Order.findOne({orderNumber:second.body.data.orderNumber});
 const url=id=>'/api/orders/'+id+'/status';
 await request(app).get('/api/orders/'+firstOrder.id).set('Authorization','Bearer '+b.token).expect(404);
 await request(app).put(url(firstOrder.id)).set('Authorization','Bearer '+b.token).send({status:'confirmed'}).expect(404);
 await request(app).put(url(firstOrder.id)).set('Authorization','Bearer '+a.token).send({status:'completed'}).expect(409);
 const results=await Promise.all([firstOrder,secondOrder].map(o=>request(app).put(url(o.id)).set('Authorization','Bearer '+a.token).send({status:'confirmed'})));
 assert.deepEqual(results.map(r=>r.status).sort(),[200,409]);
 assert.equal((await Product.findById(pa)).stock,1);
 const winner=results.find(r=>r.status===200).body.data;
 await request(app).put(url(winner._id)).set('Authorization','Bearer '+a.token).send({status:'confirmed'}).expect(200);
 assert.equal((await Product.findById(pa)).stock,1);
 for(const status of ['processing','completed'])await request(app).put(url(winner._id)).set('Authorization','Bearer '+a.token).send({status}).expect(200);
 await request(app).put(url(winner._id)).set('Authorization','Bearer '+a.token).send({status:'rejected'}).expect(409);
 const stats=await request(app).get('/api/orders/stats').set('Authorization','Bearer '+a.token).expect(200);
 assert.equal(stats.body.data.completedOrders,1);
 const list=await request(app).get('/api/orders').set('Authorization','Bearer '+b.token).expect(200);
 assert.equal(list.body.data.total,0);
 const other = await post(body(pb), 'order-test-b').expect(201);
 const otherOrder = await Order.findOne({orderNumber:other.body.data.orderNumber});
 await request(app).get('/api/orders/'+otherOrder.id).set('Authorization','Bearer '+a.token).expect(404);
 await request(app).put(url(otherOrder.id)).set('Authorization','Bearer '+b.token).send({status:'rejected'}).expect(200);
 assert.equal((await Product.findById(pb)).stock,3);
 const own = await request(app).get('/api/orders').set('Authorization','Bearer '+b.token).expect(200);
 assert.equal(own.body.data.total,1);
 await request(app).get('/api/orders/invalid').set('Authorization','Bearer '+a.token).expect(400);
});
